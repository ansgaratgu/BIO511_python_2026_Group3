# save one value of each data type to its own varibale
# print all valuables and their type

# string
a = "This is a test"
print(a)
print(type(a))

# integer
b = 16
print(b)
print(type(b))

# float
c = 16/3
print(c)
print(type(c))

# range
d = range(7)
print(d)
print(type(d))

# dictionary
e = {"country" : "Greece", "capital" : "Athens"}
print(e)
print(type(e))

# set: unordered collection of unique elements
f = {"loop", "lutz", "axel"}
print(f)
print(type(f))

# list: collection of ordered, mutable elements
h = ["loop", "lutz", "axel"]
print(h)
print(type(h))

# tuple: ordered, immutable collection of elements
# used when data should not be modified after creation
i = ("loop", "lutz", "axel")
print(i)
print(type(i))

# boolean
g = False
print(g)
print(type(g))

# nonetype
x = None
print(x)
print(type(x))

